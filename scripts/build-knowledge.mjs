/**
 * Generate functions/_lib/knowledge.generated.js for the AI chat assistant.
 * Source of truth: src/data/products.js + src/seo/siteMeta.js
 * Runs automatically before `npm run build` (prebuild). Manual: `npm run knowledge`
 */
import { readFile, writeFile, mkdir, rm } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const tmpDir = path.join(root, '.cache', 'knowledge')
const outFile = path.join(root, 'functions', '_lib', 'knowledge.generated.js')

/** products.js / siteMeta.js are Vite modules: stub image imports and import.meta.env for Node */
async function loadViteModule(relPath) {
  const src = await readFile(path.join(root, relPath), 'utf8')
  const code = src
    .replace(/^import\s+(\w+)\s+from\s+['"][^'"]+\.(webp|png|jpe?g|svg|gif|avif)['"];?\s*$/gm, 'const $1 = null')
    .replace(/import\.meta\.env/g, '({})')
  const tmpFile = path.join(tmpDir, path.basename(relPath).replace(/\.js$/, `.${Date.now()}.mjs`))
  await writeFile(tmpFile, code)
  return import(pathToFileURL(tmpFile).href)
}

const list = (arr, sep = '; ') => (Array.isArray(arr) ? arr.filter(Boolean).join(sep) : '')

function productToText(p) {
  const lines = [`## ${p.name}`, `ID: ${p.id} | Page: /products/${p.id} | Series: ${p.series}`]
  if (p.category) lines.push(`Category: ${p.category}`)
  if (p.badge || p.powerRange) lines.push(`Badge: ${p.badge || '-'} | Laser power class: ${p.powerRange || '-'}`)
  if (p.variantGroup) lines.push(`Variant group: ${p.variantGroup} (${p.variantHint || p.variantLabel || ''})`)
  if (p.description) lines.push(`Summary: ${p.description}`)
  if (p.models?.length) lines.push(`Models: ${list(p.models.map((m) => `${m.name} (${m.power})`))}`)
  if (p.keySpecs?.length) lines.push(`Key specs: ${list(p.keySpecs.map((s) => `${s.label}: ${s.value}`))}`)
  if (p.specsTable?.length) {
    lines.push('Specifications:')
    for (const row of p.specsTable) {
      const values = Object.entries(row.values || {})
        .map(([model, v]) => `${model}=${v}`)
        .join(', ')
      lines.push(`- ${row.parameter}: ${values}`)
    }
  }
  if (p.standardConfig?.length) lines.push(`Standard configuration: ${list(p.standardConfig)}`)
  if (p.optionalConfig?.length) lines.push(`Optional configuration: ${list(p.optionalConfig)}`)
  if (p.features?.length) lines.push(`Highlights: ${list(p.features)}`)
  if (p.featureDetails?.length) {
    lines.push('Feature details:')
    for (const f of p.featureDetails) lines.push(`- ${f.title}: ${f.description}`)
  }
  if (p.applications?.length) lines.push(`Applications: ${list(p.applications, ', ')}`)
  return lines.join('\n')
}

async function main() {
  await mkdir(tmpDir, { recursive: true })
  try {
    const { products } = await loadViteModule('src/data/products.js')
    const { siteMeta, homeFaqs } = await loadViteModule('src/seo/siteMeta.js')

    const company = [
      `Brand: ${siteMeta.brand} (${siteMeta.legalName})`,
      `Tagline: ${siteMeta.tagline}`,
      `About: ${siteMeta.description}`,
      `Contact email: ${siteMeta.contactEmail}`,
      `Contact phone: ${siteMeta.contactPhone}`,
      `Address: ${Object.values(siteMeta.address).filter(Boolean).join(', ')}`
    ].join('\n')

    const faqs = homeFaqs.map((f) => `Q: ${f.question}\nA: ${f.answer}`).join('\n\n')

    const knowledge = [
      '# COMPANY',
      company,
      '# PRODUCTS',
      products.map(productToText).join('\n\n'),
      '# FAQ',
      faqs
    ].join('\n\n')

    const productIndex = products.map((p) => ({ id: p.id, name: p.name }))

    const out = `// AUTO-GENERATED by scripts/build-knowledge.mjs — do not edit by hand.
// Edit src/data/products.js or src/seo/siteMeta.js, then run \`npm run knowledge\`.

export const KNOWLEDGE_TEXT = ${JSON.stringify(knowledge)}

export const PRODUCT_INDEX = ${JSON.stringify(productIndex, null, 2)}
`
    await writeFile(outFile, out)
    console.log(`[knowledge] ${products.length} products, ${homeFaqs.length} FAQs, ${knowledge.length} chars → ${path.relative(root, outFile)}`)
  } finally {
    await rm(tmpDir, { recursive: true, force: true })
  }
}

main().catch((err) => {
  console.error('[knowledge] failed:', err)
  process.exit(1)
})
